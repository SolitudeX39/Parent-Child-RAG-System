def upload_ttl_to_aura(ttl_file_path, uri, username, password):
    if not os.path.exists(ttl_file_path):
        print(f"Error: The file {ttl_file_path} was not found.")
        print("Make sure you run ner_rdflib_pipeline.py first to generate the .ttl file.")
        return

    print(f"Connecting to Neo4j at {uri}...")
    
    # 1. Define authentication dictionary required by rdflib-neo4j
    auth_data = {
        'uri': uri,
        'database': '9477a102',  # As seen in your Aura workspace
        'user': username,
        'pwd': password
    }

    # 2. Define Custom Prefixes
    # When rdflib-neo4j sees a long URI like "http://example.org/medical/Disease",
    # it needs to know how to shorten it into a clean Neo4j label like "med:Disease".
    # We must provide the same namespaces we used in our generation script.
    MED = Namespace("http://example.org/medical/")
    DISEASE = Namespace("http://example.org/medical/disease/")
    UMLS = Namespace("http://linkedlifedata.com/resource/umls/id/")

    prefixes = {
        "med": MED,
        "disease": DISEASE,
        "umls": UMLS
    }

    # 3. Configure the rdflib-neo4j adapter
    print("Configuring RDFLib to use Neo4jStore...")
    config = Neo4jStoreConfig(
        auth_data=auth_data,
        custom_prefixes=prefixes,
        handle_vocab_uri_strategy=HANDLE_VOCAB_URI_STRATEGY.SHORTEN, # Tells it to use the prefixes to shorten URIs
        batching=True  # Highly recommended for bulk data inserts
    )
    
    # 4. Initialize the Neo4jStore with the config 
    try:
        store = Neo4jStore(config=config)
    except Exception as e:
        print(f"Failed to initialize Neo4j connection. Check your credentials and URI: {e}")
        return

    # 5. Create an RDFLib graph that treats Neo4j as its underlying storage
    g = Graph(store=store)

    print(f"Uploading data from {ttl_file_path} to Neo4j...")
    print("(As it parses the file, it automatically streams Nodes & Relationships)")
    
    try:
        # The 'parse' command streams the data directly into Neo4j
        g.parse(ttl_file_path, format="turtle")
        print("\nUpload completed successfully!")
    except Exception as e:
        print(f"\nAn error occurred during upload: {e}")
    finally:
        # 6. Important Step! 
        # Because we set batching=True, we MUST close the graph with True (which means commit)
        # to ensure the final batch of nodes is successfully written to the database.
        try:
            g.close(True)
            print("Connection closed safely.")
        except Exception as e:
            print(f"Error while closing connection: {e}")

