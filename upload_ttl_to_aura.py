import os
from rdflib import Graph, Namespace
from rdflib_neo4j import Neo4jStoreConfig, Neo4jStore, HANDLE_VOCAB_URI_STRATEGY

# ==========================================
# SETUP INSTRUCTIONS:
# pip install neo4j rdflib-neo4j rdflib
